#!/usr/bin/env node
// @ts-check
"use strict";

const fs = require("node:fs");
const path = require("node:path");
const { parseStrictJson } = require("../lib/agent/strict-json.js");

const CLI_ROOT = path.resolve(__dirname, "..");
const SOURCE_PATH = path.join(CLI_ROOT, "commands", "agent", "renderer-registry.v1.json");
const OUTPUT_PATH = path.join(CLI_ROOT, "lib", "agent", "renderer-registry.generated.js");
const FORMAT_FIELDS = Object.freeze(["appendOnly", "color", "mode", "name", "stderr", "stdout", "structured"]);
const EXPECTED = Object.freeze([
  ["text", "final", false, "final-response-only", "none", "never", true],
  ["markdown", "final", false, "final-response-and-references", "none", "never", true],
  ["json", "final", true, "one-schema-versioned-document", "none", "never", true],
  ["jsonl", "events", true, "accepted-protocol-events", "none", "never", true],
  ["tty", "events", false, "model-content", "status-progress-references-tools-diagnostics", "tty-only-unless-no-color", true],
]);

function exactFields(value, fields, label) {
  if (!value || typeof value !== "object" || Array.isArray(value) || Object.getPrototypeOf(value) !== Object.prototype || Object.keys(value).sort().join("|") !== [...fields].sort().join("|")) throw new Error(`${label} fields are not exact`);
}

function validateDefinition(value) {
  exactFields(value, ["defaultFormat", "formats", "schemaVersion", "task"], "renderer registry");
  if (value.schemaVersion !== "agent-fai-renderer-registry.v1" || value.task !== "AFCLI-T016" || value.defaultFormat !== "tty") throw new Error("renderer registry identity is invalid");
  if (!Array.isArray(value.formats) || value.formats.length !== EXPECTED.length) throw new Error("renderer format cardinality is invalid");
  const tuples = value.formats.map((format) => {
    exactFields(format, FORMAT_FIELDS, "renderer format");
    if (typeof format.name !== "string" || typeof format.mode !== "string" || typeof format.structured !== "boolean" || typeof format.stdout !== "string" || typeof format.stderr !== "string" || typeof format.color !== "string" || format.appendOnly !== true) throw new Error("renderer format value is invalid");
    return [format.name, format.mode, format.structured, format.stdout, format.stderr, format.color, format.appendOnly];
  });
  if (JSON.stringify(tuples) !== JSON.stringify(EXPECTED)) throw new Error("renderer format set is invalid");
  return value;
}

function readDefinition() {
  return validateDefinition(parseStrictJson(fs.readFileSync(SOURCE_PATH, "utf8"), "Agent FAI renderer registry"));
}

function createRuntimeRegistry(definition) {
  const formats = Object.freeze(definition.formats.map((format) => Object.freeze({ ...format })));
  const names = Object.freeze(formats.map((format) => format.name));
  const lookup = (name) => formats.find((format) => format.name === name) || null;
  return Object.freeze({ schemaVersion: definition.schemaVersion, task: definition.task, defaultFormat: definition.defaultFormat, formats, names, lookup });
}

function generateRendererRegistry(candidate) {
  const definition = validateDefinition(candidate || readDefinition());
  return [
    "// Generated by scripts/generate-agent-renderer-registry.js. Do not edit.",
    "// @ts-check",
    '"use strict";',
    "",
    `const definition = ${JSON.stringify(definition, null, 2)};`,
    "",
    `const createRuntimeRegistry = ${createRuntimeRegistry.toString()};`,
    "",
    "module.exports = createRuntimeRegistry(definition);",
    "",
  ].join("\n");
}

function main(argv = process.argv.slice(2)) {
  const output = generateRendererRegistry();
  if (argv.includes("--write")) { fs.writeFileSync(OUTPUT_PATH, output, "utf8"); return 0; }
  if (argv.includes("--check")) return fs.existsSync(OUTPUT_PATH) && fs.readFileSync(OUTPUT_PATH, "utf8") === output ? 0 : 1;
  process.stdout.write(output);
  return 0;
}

if (require.main === module) process.exitCode = main();
module.exports = { OUTPUT_PATH, SOURCE_PATH, createRuntimeRegistry, generateRendererRegistry, readDefinition, validateDefinition, main };