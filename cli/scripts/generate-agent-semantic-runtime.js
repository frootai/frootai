#!/usr/bin/env node
// @ts-check
"use strict";

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { spawnSync } = require("node:child_process");

const CLI_ROOT = path.resolve(__dirname, "..");
const REPOSITORY = path.resolve(CLI_ROOT, "..", "..", "frootai-agent-fai-cli-contracts");
const SOURCE_COMMIT = "bbd9002f5bbaaa87ce08bc4c06c0b8d071c35640";
const SOURCE_PATH = "scripts/validate-agent-fai-contracts.cjs";
const SOURCE_BLOB = "d8e30e0fd993371fd8f3c2de196dba76c5c9af50";
const ADAPTER_PATH = path.join(CLI_ROOT, "scripts", "semantic-runtime-adapter.js");
const OUTPUT_PATH = path.join(CLI_ROOT, "lib", "agent", "semantic-runtime.generated.js");

function git(args) {
  const result = spawnSync("git", ["-C", REPOSITORY, ...args], { encoding: "utf8", windowsHide: true, maxBuffer: 8 * 1024 * 1024 });
  if (result.status !== 0) throw new Error("Unable to read pinned T006 semantic source");
  return result.stdout;
}

function extractFunction(source, name) {
  const start = source.indexOf(`function ${name}(`);
  if (start < 0) throw new Error(`Pinned T006 function ${name} is missing`);
  const bodyStart = source.indexOf("{", start);
  let depth = 0; let quote = null; let escaped = false; let lineComment = false; let blockComment = false;
  for (let index = bodyStart; index < source.length; index += 1) {
    const character = source[index]; const next = source[index + 1];
    if (lineComment) { if (character === "\n") lineComment = false; continue; }
    if (blockComment) { if (character === "*" && next === "/") { blockComment = false; index += 1; } continue; }
    if (quote) { if (escaped) escaped = false; else if (character === "\\") escaped = true; else if (character === quote) quote = null; continue; }
    if (character === "/" && next === "/") { lineComment = true; index += 1; continue; }
    if (character === "/" && next === "*") { blockComment = true; index += 1; continue; }
    if (["\"", "'", "`"].includes(character)) { quote = character; continue; }
    if (character === "{") depth += 1;
    if (character === "}" && --depth === 0) return source.slice(start, index + 1);
  }
  throw new Error(`Pinned T006 function ${name} is unterminated`);
}

function readPinnedSource() {
  const source = git(["show", `${SOURCE_COMMIT}:${SOURCE_PATH}`]);
  const blob = git(["rev-parse", `${SOURCE_COMMIT}:${SOURCE_PATH}`]).trim();
  if (blob !== SOURCE_BLOB) throw new Error("Pinned T006 semantic source blob drifted");
  return source;
}

function generateSemanticRuntime() {
  const source = readPinnedSource();
  const constantsStart = source.indexOf("const EVENT_FIELDS =");
  const constantsEnd = source.indexOf("const EXIT_BY_ERROR =");
  if (constantsStart < 0 || constantsEnd < constantsStart) throw new Error("Pinned T006 semantic constants changed");
  const constants = source.slice(constantsStart, constantsEnd).trim();
  const functions = ["assertUnicodeScalarString", "canonicalJson", "replayReduceEvents", "validateTimestamps", "validateEvent", "validateEventStream"].map((name) => extractFunction(source, name)).join("\n\n");
  const adapterSource = fs.readFileSync(ADAPTER_PATH, "utf8");
  const adapter = extractFunction(adapterSource, "createEventStreamTracker");
  const adapterDigest = crypto.createHash("sha256").update(adapter).digest("hex");
  return `// Generated by scripts/generate-agent-semantic-runtime.js. Do not edit.\n// T006 source: ${SOURCE_COMMIT}:${SOURCE_PATH}\n// T006 Git blob: ${SOURCE_BLOB}\n// Incremental adapter SHA-256: ${adapterDigest}\n// @ts-check\n"use strict";\n\n${constants}\n\n${functions}\n\nconst validateEventSemantics = validateEvent;\nconst sameBindings = (left, right) => canonicalJson([...left].sort()) === canonicalJson([...right].sort());\n\n${adapter}\n\nmodule.exports = { ACTION_CONTRACTS, TERMINAL_EVENTS, canonicalJson, createEventStreamTracker, validateEventSemantics, validateEventStream };\n`;
}

function main(argv = process.argv.slice(2)) {
  const output = generateSemanticRuntime();
  if (argv.includes("--write")) { fs.writeFileSync(OUTPUT_PATH, output, "utf8"); return 0; }
  if (argv.includes("--check")) return fs.existsSync(OUTPUT_PATH) && fs.readFileSync(OUTPUT_PATH, "utf8") === output ? 0 : 1;
  process.stdout.write(output); return 0;
}

if (require.main === module) process.exitCode = main();
module.exports = { ADAPTER_PATH, OUTPUT_PATH, SOURCE_BLOB, SOURCE_COMMIT, SOURCE_PATH, generateSemanticRuntime, main };