/**
 * FAI Engine — Harness Materializer
 * Renders the files a play's harness profiles own (for example
 * .github/instructions/security.instructions.md) so hosts that read physical
 * files, such as GitHub Copilot, receive the inherited harness. Check mode
 * reports drift; write mode regenerates.
 */

import { closeSync, constants, fstatSync, lstatSync, mkdirSync, openSync, readFileSync, renameSync, unlinkSync, writeFileSync } from 'fs';
import { randomUUID } from 'crypto';
import { dirname, isAbsolute, relative, resolve } from 'path';
import { compileManifest, DEFAULT_PROFILES_ROOT } from './harness-resolver.js';

const PLACEHOLDER = /\{\{\s*([A-Za-z.]+)\s*\}\}/g;

function playTitle(play) {
  return play.replace(/^\d+-/, '').split('-').map(word => word.charAt(0).toUpperCase() + word.slice(1)).join(' ');
}

function renderTemplate(text, values) {
  const unknown = new Set();
  const content = text.replace(PLACEHOLDER, (match, key) => {
    if (!(key in values)) {
      unknown.add(key);
      return match;
    }
    return values[key];
  });
  return { content, unknown: [...unknown] };
}

function withMarker(content, marker) {
  if (content.startsWith('---\n')) {
    const end = content.indexOf('\n---\n', 3);
    if (end !== -1) {
      const split = end + '\n---\n'.length;
      return `${content.slice(0, split)}\n${marker}\n${content.slice(split)}`;
    }
  }
  return `${marker}\n\n${content}`;
}

function normalize(text) {
  return text.replace(/\r\n/g, '\n');
}

/**
 * Render every profile-owned file for a compiled manifest.
 * @param {{ manifest: object, playDir: string, harness: object }} compiled - compileManifest result
 * @param {string} repoRoot - Repository root used to locate templates
 * @param {{ marker?: boolean }} [options] - omit the generated marker when comparing hand-copied files
 * @returns {{ files: Array<{ target: string, absolute: string, content: string }>, errors: string[] }}
 */
function renderHarnessFiles(compiled, repoRoot, { marker = true } = {}) {
  const errors = [];
  const files = [];
  const subject = compiled.effective?.subject ?? compiled.manifest?.play;
  const kind = compiled.effective?.kind ?? 'solution-play';
  const subjectDir = compiled.subjectDir ?? compiled.playDir;
  const values = {
    'play.id': subject,
    'play.title': playTitle(subject),
    'subject.id': subject,
    'subject.title': compiled.effective?.display_name ?? playTitle(subject),
    'subject.kind': kind
  };

  for (const file of compiled.harness.files) {
    const absolute = resolve(subjectDir, file.target);
    const rel = relative(subjectDir, absolute);
    if (rel.startsWith('..') || isAbsolute(rel)) {
      errors.push(`${file.target} escapes the subject directory`);
      continue;
    }
    const { content, unknown } = renderTemplate(normalize(readFileSync(resolve(repoRoot, file.template), 'utf8')), values);
    if (unknown.length > 0) {
      errors.push(`${file.template} uses unknown placeholders: ${unknown.join(', ')} (allowed: ${Object.keys(values).join(', ')})`);
      continue;
    }
    const writeCommand = kind === 'solution-play' ? 'npm run harness:write' : 'npm run platform:harness:write';
    const note = `<!-- Generated by FAI harness profile ${file.profile} from ${file.template}. Do not edit here; change the template and run ${writeCommand}. -->`;
    files.push({ target: file.target, absolute, content: marker ? withMarker(content, note) : content });
  }

  return { files, errors };
}

function applyRenderedFiles(rendered, { write = false } = {}) {
  const results = [];
  const errors = [...rendered.errors];
  for (const file of rendered.files) {
    let status = 'missing';
    let descriptor;
    try {
      descriptor = openSync(file.absolute, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0));
      const opened = fstatSync(descriptor);
      const current = lstatSync(file.absolute);
      if (current.isSymbolicLink() || current.dev !== opened.dev || current.ino !== opened.ino) {
        errors.push(`${file.target} is a symbolic link or changed while opening; refusing to materialize`);
        continue;
      }
      status = normalize(readFileSync(descriptor, 'utf8')) === file.content ? 'unchanged' : 'drift';
    } catch (error) {
      if (error.code === 'ELOOP') {
        errors.push(`${file.target} is a symbolic link; refusing to materialize`);
        continue;
      }
      if (error.code !== 'ENOENT') throw error;
    } finally {
      if (descriptor !== undefined) closeSync(descriptor);
    }
    if (write && status !== 'unchanged') {
      mkdirSync(dirname(file.absolute), { recursive: true });
      const temporary = resolve(dirname(file.absolute), `.fai-harness-${randomUUID()}.tmp`);
      try {
        writeFileSync(temporary, file.content, { encoding: 'utf8', flag: 'wx', mode: 0o600 });
        renameSync(temporary, file.absolute);
      } finally {
        try { unlinkSync(temporary); } catch (error) { if (error.code !== 'ENOENT') throw error; }
      }
      status = status === 'missing' ? 'created' : 'updated';
    }
    results.push({ target: file.target, status });
  }
  return { files: results, errors };
}

/**
 * Check (default) or regenerate the profile-owned files of one play.
 * @param {string} manifestPath - Path to fai-manifest.json
 * @param {{ write?: boolean, now?: Date, profilesRoot?: string }} [options]
 * @returns {{ play: string|null, extends: string|null, files: Array<{ target: string, status: string }>, errors: string[] }}
 */
function materializePlay(manifestPath, { write = false, now, profilesRoot } = {}) {
  const options = { ...(now && { now }), ...(profilesRoot && { profilesRoot }) };
  const compiled = compileManifest(manifestPath, options);
  const play = compiled.manifest?.play ?? null;
  if (!compiled.harness) return { play, extends: null, files: [], errors: compiled.errors };
  if (compiled.errors.length > 0) return { play, extends: compiled.harness.extends, files: [], errors: compiled.errors };

  const repoRoot = resolve(profilesRoot ?? DEFAULT_PROFILES_ROOT, '..', '..');
  const rendered = renderHarnessFiles(compiled, repoRoot);
  const applied = applyRenderedFiles(rendered, { write });
  return { play, extends: compiled.harness.extends, files: applied.files, errors: applied.errors };
}

export { applyRenderedFiles, materializePlay, normalize, renderHarnessFiles, playTitle };
