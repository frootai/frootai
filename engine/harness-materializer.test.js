import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { materializePlay, playTitle } from './harness-materializer.js';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = '.github/instructions/security.instructions.md';

function fixture({ template = '---\ndescription: "Rules for {{play.title}}"\n---\n\n# {{play.title}} ({{play.id}})\n', files = [TARGET] } = {}) {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'fai-materialize-')));
  const profilesRoot = path.join(root, 'harness', 'profiles');
  const profileDir = path.join(profilesRoot, 'base');
  fs.mkdirSync(path.join(profileDir, 'files', '.github', 'instructions'), { recursive: true });
  fs.writeFileSync(path.join(profileDir, 'v1.json'), JSON.stringify({ profile: 'base', version: '1.0.0', files }));
  fs.writeFileSync(path.join(profileDir, 'files', TARGET), template);
  const playDir = path.join(root, 'solution-plays', '07-multi-agent-service');
  fs.mkdirSync(path.join(playDir, 'spec'), { recursive: true });
  const manifestPath = path.join(playDir, 'spec', 'fai-manifest.json');
  fs.writeFileSync(manifestPath, JSON.stringify({
    play: '07-multi-agent-service',
    version: '1.0.0',
    extends: 'base@1',
    context: { knowledge: ['F1-GenAI-Foundations'], waf: ['security'] },
    primitives: {}
  }));
  return {
    profilesRoot,
    manifestPath,
    output: path.join(playDir, TARGET),
    run: (write = false) => materializePlay(manifestPath, { write, profilesRoot }),
    cleanup: () => fs.rmSync(root, { recursive: true, force: true })
  };
}

test('playTitle matches the title used by existing play copies', () => {
  assert.equal(playTitle('01-enterprise-rag'), 'Enterprise Rag');
  assert.equal(playTitle('102-azure-cost-optimizer'), 'Azure Cost Optimizer');
});

test('check mode reports missing files without writing', () => {
  const f = fixture();
  try {
    const result = f.run();
    assert.deepEqual(result.errors, []);
    assert.deepEqual(result.files, [{ target: TARGET, status: 'missing' }]);
    assert.equal(fs.existsSync(f.output), false);
  } finally {
    f.cleanup();
  }
});

test('write mode renders placeholders and a marker after front matter, then becomes unchanged', () => {
  const f = fixture();
  try {
    assert.deepEqual(f.run(true).files, [{ target: TARGET, status: 'created' }]);
    const content = fs.readFileSync(f.output, 'utf8');
    assert.match(content, /^---\ndescription: "Rules for Multi Agent Service"\n---\n\n<!-- Generated by FAI harness profile base@1 /);
    assert.match(content, /# Multi Agent Service \(07-multi-agent-service\)\n$/);
    assert.deepEqual(f.run().files, [{ target: TARGET, status: 'unchanged' }]);
  } finally {
    f.cleanup();
  }
});

test('hand edits are reported as drift and regenerated on write', () => {
  const f = fixture();
  try {
    f.run(true);
    fs.appendFileSync(f.output, '\nlocal edit\n');
    assert.deepEqual(f.run().files, [{ target: TARGET, status: 'drift' }]);
    assert.deepEqual(f.run(true).files, [{ target: TARGET, status: 'updated' }]);
    assert.doesNotMatch(fs.readFileSync(f.output, 'utf8'), /local edit/);
  } finally {
    f.cleanup();
  }
});

test('CRLF working-tree copies are not treated as drift', () => {
  const f = fixture();
  try {
    f.run(true);
    fs.writeFileSync(f.output, fs.readFileSync(f.output, 'utf8').replace(/\n/g, '\r\n'));
    assert.deepEqual(f.run().files, [{ target: TARGET, status: 'unchanged' }]);
  } finally {
    f.cleanup();
  }
});

test('regeneration atomically replaces a hard link without modifying its other name', () => {
  const instance = fixture();
  try {
    instance.run(true);
    fs.unlinkSync(instance.output);
    const other = `${instance.output}.other`;
    fs.writeFileSync(other, 'preserve the other file');
    fs.linkSync(other, instance.output);
    assert.deepEqual(instance.run(true).files, [{ target: TARGET, status: 'updated' }]);
    assert.equal(fs.readFileSync(other, 'utf8'), 'preserve the other file');
    assert.deepEqual(instance.run().files, [{ target: TARGET, status: 'unchanged' }]);
    assert.equal(fs.readdirSync(path.dirname(instance.output)).some(name => name.endsWith('.tmp')), false);
  } finally {
    instance.cleanup();
  }
});

test('unknown placeholders fail without writing', () => {
  const f = fixture({ template: '# {{play.owner}}\n' });
  try {
    const result = f.run(true);
    assert.ok(result.errors.some(e => e.includes('unknown placeholders: play.owner')), result.errors.join('\n'));
    assert.equal(fs.existsSync(f.output), false);
  } finally {
    f.cleanup();
  }
});

test('file targets outside .github or escaping the play are rejected by the profile', () => {
  for (const target of ['README.md', '.github/../../evil.md', '.github/hooks/run.sh']) {
    const f = fixture({ files: [target] });
    try {
      const result = f.run(true);
      assert.ok(result.errors.some(e => e.includes('file target must be')), `${target}: ${result.errors.join('\n')}`);
    } finally {
      f.cleanup();
    }
  }
});

test('every harnessed play in this repository is in sync with its profiles', () => {
  const playsRoot = path.join(repoRoot, 'solution-plays');
  const problems = [];
  for (const play of fs.readdirSync(playsRoot).filter(name => /^\d{2,3}-/.test(name))) {
    const manifestPath = path.join(playsRoot, play, 'spec', 'fai-manifest.json');
    if (!fs.existsSync(manifestPath)) continue;
    const result = materializePlay(manifestPath);
    if (!result.extends) continue;
    problems.push(...result.errors.map(e => `${play}: ${e}`));
    problems.push(...result.files.filter(file => file.status !== 'unchanged').map(file => `${play}: ${file.target} ${file.status}`));
  }
  assert.deepEqual(problems, []);
});
