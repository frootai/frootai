/**
 * FAI Engine — Harness Migrator
 * Rewrites a legacy fai-manifest.json to `extends` a harness profile without
 * weakening it: profile-provided hooks and instructions are removed from the
 * manifest, guardrails move into primitives.guardrails and only stricter values
 * stay, and the rewrite is compiled and compared before anything is written.
 */

import { existsSync, readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import { compileManifestData, DEFAULT_PROFILES_ROOT, isLooser, loadProfileChain } from './harness-resolver.js';
import { normalize, renderHarnessFiles } from './harness-materializer.js';
import { playDirFor } from './manifest-reader.js';

const LIST_CATEGORIES = ['instructions', 'hooks'];

/**
 * Profile a legacy play should adopt: Azure plays with Bicep/ARM infrastructure get the Azure profile.
 * @param {object} manifest
 * @returns {string}
 */
function selectProfile(manifest) {
  return manifest.infrastructure?.bicep || manifest.infrastructure?.template ? 'azure-ai-standard@1' : 'agent-standard@1';
}

function targetOf(playDir, entry) {
  return resolve(playDir, entry).replace(/[\\/]+$/, '');
}

/**
 * Plan (and optionally write) the migration of one play.
 * @param {string} manifestPath
 * @param {{ write?: boolean, now?: Date, profilesRoot?: string, profile?: string }} [options]
 * @returns {{ play: string|null, status: string, profile: string|null, reasons: string[], changes: string[], content?: string }}
 */
function migratePlay(manifestPath, { write = false, now = new Date(), profilesRoot = DEFAULT_PROFILES_ROOT, profile } = {}) {
  const raw = normalize(readFileSync(manifestPath, 'utf8'));
  const manifest = JSON.parse(raw);
  const play = manifest.play ?? null;
  if (manifest.extends !== undefined) return { play, status: 'harnessed', profile: manifest.extends, reasons: [], changes: [] };

  const reference = profile ?? selectProfile(manifest);
  const { chain, errors: chainErrors } = loadProfileChain(reference, profilesRoot);
  if (chainErrors.length > 0) return { play, status: 'blocked', profile: reference, reasons: chainErrors, changes: [] };

  const playDir = playDirFor(manifestPath);
  const repoRoot = resolve(profilesRoot, '..', '..');
  const reasons = [];
  const changes = [];

  // Guardrails: one source of truth, nothing looser than the profile.
  const baseline = {};
  for (const { profile: p } of chain) Object.assign(baseline, p.primitives?.guardrails || {});
  const top = manifest.guardrails;
  const nested = manifest.primitives?.guardrails;
  if (top && nested && JSON.stringify(top) !== JSON.stringify(nested)) reasons.push('declares different top-level and primitives guardrails');
  const declared = nested ?? top ?? {};
  const looser = Object.entries(declared).filter(([key, value]) => key in baseline && isLooser(key, value, baseline[key])).map(([key]) => key);
  if (looser.length > 0) reasons.push(`declares guardrails looser than ${reference}: ${looser.join(', ')} (needs an owner-approved waiver)`);

  // Profile-owned files must currently be the shared template, so regeneration loses nothing.
  const probe = compileManifestData({ ...manifest, extends: reference, guardrails: undefined }, manifestPath, { now, profilesRoot });
  if (probe.harness) {
    const rendered = renderHarnessFiles(probe, repoRoot, { marker: false });
    reasons.push(...rendered.errors);
    for (const file of rendered.files) {
      if (!existsSync(file.absolute)) continue;
      const current = normalize(readFileSync(file.absolute, 'utf8'));
      if (current !== file.content && !current.includes('<!-- Generated by FAI harness profile')) {
        reasons.push(`${file.target} has play-specific content`);
      }
    }
    for (const requirement of probe.harness.requires) {
      if (!existsSync(resolve(playDir, requirement.path))) reasons.push(`missing required ${requirement.path}`);
    }
  }
  if (reasons.length > 0) return { play, status: 'blocked', profile: reference, reasons, changes };

  // Rewrite: extends right after version, original key order otherwise.
  const next = {};
  for (const [key, value] of Object.entries(manifest)) {
    if (key === 'guardrails') continue;
    next[key] = structuredClone(value);
    if (key === 'version') next.extends = reference;
  }
  if (!('extends' in next)) next.extends = reference;
  next.primitives ||= {};

  const provided = new Set();
  for (const { profile: p } of chain) {
    for (const category of LIST_CATEGORIES) {
      for (const entry of p.primitives?.[category] || []) provided.add(`${category}:${resolve(repoRoot, entry).replace(/[\\/]+$/, '')}`);
    }
  }
  for (const category of LIST_CATEGORIES) {
    const list = next.primitives[category];
    if (!Array.isArray(list)) continue;
    const kept = list.filter(entry => !provided.has(`${category}:${targetOf(playDir, entry)}`));
    if (kept.length !== list.length) changes.push(`primitives.${category}: ${list.length - kept.length} entr${list.length - kept.length === 1 ? 'y' : 'ies'} now inherited`);
    if (kept.length > 0) next.primitives[category] = kept;
    else delete next.primitives[category];
  }

  const stricter = Object.fromEntries(Object.entries(declared).filter(([key, value]) => !(key in baseline) || value !== baseline[key]));
  if (top) changes.push('guardrails: moved from top level (previously ignored by the engine)');
  const dropped = Object.keys(declared).length - Object.keys(stricter).length;
  if (dropped > 0) changes.push(`guardrails: ${dropped} value(s) equal to profile defaults now inherited`);
  if (Object.keys(stricter).length > 0) next.primitives.guardrails = stricter;
  else delete next.primitives.guardrails;

  // Verify before writing: compiles cleanly and nothing the play declared is lost.
  const compiled = compileManifestData(next, manifestPath, { now, profilesRoot });
  const verification = [...compiled.errors];
  if (compiled.harness) {
    const effective = compiled.manifest;
    for (const pillar of manifest.context?.waf || []) {
      if (!effective.context.waf.includes(pillar)) verification.push(`lost WAF pillar ${pillar}`);
    }
    for (const category of LIST_CATEGORIES) {
      const targets = new Set((effective.primitives[category] || []).map(entry => targetOf(playDir, entry)));
      for (const entry of manifest.primitives?.[category] || []) {
        if (!targets.has(targetOf(playDir, entry))) verification.push(`lost ${category} ${entry}`);
      }
    }
    for (const [key, value] of Object.entries(declared)) {
      if (effective.primitives.guardrails?.[key] !== value) {
        verification.push(`guardrails.${key} would change from ${value} to ${effective.primitives.guardrails?.[key]}`);
      }
    }
  }
  if (verification.length > 0) return { play, status: 'blocked', profile: reference, reasons: verification, changes };

  const content = `${JSON.stringify(next, null, 2)}\n`;
  if (write) writeFileSync(manifestPath, content, 'utf8');
  return { play, status: write ? 'migrated' : 'eligible', profile: reference, reasons: [], changes, content };
}

export { migratePlay, selectProfile };
