import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { materializeHarnessSubject } from './harness-subject-materializer.js';

function fixture(t) {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'fai-subject-materialize-')));
  const profilesRoot = path.join(root, 'harness', 'profiles');
  const profileRoot = path.join(profilesRoot, 'base');
  const subjectRoot = path.join(root, 'products', 'sample');
  const descriptorPath = path.join(root, 'harness', 'subjects', 'sample.json');
  fs.mkdirSync(path.join(profileRoot, 'files', '.github', 'instructions'), { recursive: true });
  fs.mkdirSync(subjectRoot, { recursive: true });
  fs.mkdirSync(path.dirname(descriptorPath), { recursive: true });
  fs.writeFileSync(path.join(subjectRoot, 'README.md'), '# Sample\n');
  fs.writeFileSync(path.join(profileRoot, 'files', '.github', 'instructions', 'harness.md'), '# {{subject.title}}\n\nKind: {{subject.kind}}\n');
  fs.writeFileSync(path.join(profileRoot, 'v1.json'), JSON.stringify({
    profile: 'base', version: '1.0.0', description: 'Materializer fixture profile.',
    files: ['.github/instructions/harness.md'], requires: { paths: ['README.md'] }
  }));
  fs.writeFileSync(descriptorPath, JSON.stringify({
    subject: 'sample-product', kind: 'product', version: '1.0.0', root: 'products/sample',
    context: { knowledge: ['F1-GenAI-Foundations'], waf: ['security'] }, primitives: {}
  }));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  return { root, profilesRoot, descriptorPath, generated: path.join(subjectRoot, '.github', 'instructions', 'harness.md') };
}

test('check, write, unchanged and drift states work for a generic subject', (t) => {
  const f = fixture(t);
  const options = { repoRoot: f.root, profilesRoot: f.profilesRoot, defaultProfile: 'base@1' };
  assert.equal(materializeHarnessSubject(f.descriptorPath, options).files[0].status, 'missing');
  assert.equal(materializeHarnessSubject(f.descriptorPath, { ...options, write: true }).files[0].status, 'created');
  const content = fs.readFileSync(f.generated, 'utf8');
  assert.match(content, /# Sample Product/);
  assert.match(content, /Kind: product/);
  assert.match(content, /Generated by FAI harness profile base@1/);
  assert.match(content, /npm run platform:harness:write/);
  assert.equal(materializeHarnessSubject(f.descriptorPath, options).files[0].status, 'unchanged');
  fs.appendFileSync(f.generated, '\nhand edit\n');
  assert.equal(materializeHarnessSubject(f.descriptorPath, options).files[0].status, 'drift');
});
