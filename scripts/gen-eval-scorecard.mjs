#!/usr/bin/env node
// gen-eval-scorecard.mjs — [Q2] Auto eval-scorecard generator.
//
// Reads the REAL eval reports under frootai/reports/ and frootai/evaluation/
// and injects a markdown scorecard between the
// <!-- EVAL-SCORECARD --> / <!-- /EVAL-SCORECARD --> markers in README.md.
//
// Honesty contract:
//  - Numbers are READ from the report JSON, never hand-written.
//  - No per-vendor (Claude/GPT/Gemini) columns are emitted, because no
//    per-vendor eval data exists in the repo. We report what is real:
//    spec conformance, scenario pass-rate, and description-quality tiers.
//  - Output is deterministic (no timestamps), so re-running is idempotent.
//
// Usage:  node scripts/gen-eval-scorecard.mjs            (writes README.md)
//         node scripts/gen-eval-scorecard.mjs --check    (exit 1 if out of date)

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const README = join(ROOT, 'README.md');
const OPEN = '<!-- EVAL-SCORECARD -->';
const CLOSE = '<!-- /EVAL-SCORECARD -->';

function readJson(rel) {
  return JSON.parse(readFileSync(join(ROOT, rel), 'utf8'));
}

function pct(n, d) {
  if (!d) return '0%';
  return `${Math.round((n / d) * 1000) / 10}%`;
}

function buildScorecard() {
  const spec = readJson('reports/spec-conformance.json');
  const scenario = readJson('reports/scenario-eval.json');
  const desc = readJson('reports/skill-description-scores.json');
  const cfg = readJson('evaluation/eval-config.json');

  // Scenario aggregate (per-skill passed/total/score).
  const skills = Array.isArray(scenario.skills) ? scenario.skills : [];
  const scenPassed = skills.reduce((a, s) => a + (s.passed || 0), 0);
  const scenTotal = skills.reduce((a, s) => a + (s.total || 0), 0);
  const scenSkills = skills.length;
  const scenMean =
    scenSkills > 0
      ? Math.round((skills.reduce((a, s) => a + (s.score || 0), 0) / scenSkills) * 10) / 10
      : 0;

  const tiers = desc.sensei_tiers || {};
  const metrics = Array.isArray(cfg.metrics) ? cfg.metrics.join(' · ') : '';

  const lines = [];
  lines.push('<!-- Auto-generated by scripts/gen-eval-scorecard.mjs (phase Q2). Do not edit by hand. -->');
  lines.push('');
  lines.push('| Eval gate | Result | Coverage |');
  lines.push('|---|---|---|');
  lines.push(`| **Spec conformance** (skills-ref ${spec.version ?? ''}) | **${spec.valid}/${spec.total} valid** (${pct(spec.valid, spec.total)}) | ${spec.total} skills |`);
  lines.push(`| **Scenario evals** (code-pattern checks) | **${scenPassed}/${scenTotal} passed** (${pct(scenPassed, scenTotal)}) · mean score ${scenMean} | ${scenSkills} skills |`);
  lines.push(`| **Description quality** (Sensei score) | mean **${desc.mean}** · High ${tiers.High ?? 0} · Medium ${tiers.Medium ?? 0} · Low ${tiers.Low ?? 0} | ${desc.total} skills |`);
  if (metrics) {
    lines.push(`| **Quality metrics tracked** | ${metrics} | thresholds in \`evaluation/eval-config.json\` |`);
  }
  lines.push('');
  lines.push('_Generated from [`reports/`](./reports) by `scripts/gen-eval-scorecard.mjs` — `npm run scorecard`. Numbers are read from the eval reports, never hand-edited._');

  return lines.join('\n');
}

function inject(readme, block) {
  const start = readme.indexOf(OPEN);
  const end = readme.indexOf(CLOSE);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`EVAL-SCORECARD markers not found or malformed in README.md`);
  }
  const before = readme.slice(0, start + OPEN.length);
  const after = readme.slice(end);
  return `${before}\n${block}\n${after}`;
}

const check = process.argv.includes('--check');
const readme = readFileSync(README, 'utf8');
const next = inject(readme, buildScorecard());

if (check) {
  if (next !== readme) {
    console.error('EVAL-SCORECARD is out of date. Run: npm run scorecard');
    process.exit(1);
  }
  console.log('EVAL-SCORECARD up to date.');
} else {
  if (next !== readme) {
    writeFileSync(README, next);
    console.log('EVAL-SCORECARD updated in README.md');
  } else {
    console.log('EVAL-SCORECARD already up to date (no change).');
  }
}
