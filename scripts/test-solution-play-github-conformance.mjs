import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';
import { sha256, writeGithubAdapter } from './solution-play-github-adapter.mjs';
import { validateGithubAdapter } from './validate-solution-play-github-adapter.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fixtureRoot = path.join(root, 'tests', 'fixtures', 'solution-play-github-adapter');
const validatorPath = path.join(root, 'scripts', 'validate-solution-play-github-adapter.mjs');

function fixture(name = 'applicable.json') {
  return JSON.parse(fs.readFileSync(path.join(fixtureRoot, name), 'utf8'));
}

function generated(t, name = 'applicable.json') {
  const parent = fs.mkdtempSync(path.join(os.tmpdir(), 'frootai-github-conformance-'));
  const output = path.join(parent, 'output');
  const document = fixture(name);
  writeGithubAdapter(document, output);
  t.after(() => fs.rmSync(parent, { recursive: true, force: true }));
  return { document, output };
}

function replace(filePath, oldValue, newValue) {
  const content = fs.readFileSync(filePath, 'utf8');
  assert.equal(content.includes(oldValue), true, `expected mutation anchor in ${filePath}`);
  fs.writeFileSync(filePath, content.replace(oldValue, newValue), 'utf8');
}

function errorsFor(document, output) {
  const result = validateGithubAdapter(document, output);
  assert.equal(result.valid, false, 'mutated adapter must fail validation');
  return result.errors.join('\n');
}

test('accepts applicable and not-applicable projections, including Git metadata', (t) => {
  const applicable = generated(t);
  fs.mkdirSync(path.join(applicable.output, '.git'));
  assert.deepEqual(validateGithubAdapter(applicable.document, applicable.output).errors, []);
  assert.equal(validateGithubAdapter(applicable.document, applicable.output).valid, true);

  const notApplicable = generated(t, 'not-applicable.json');
  const result = validateGithubAdapter(notApplicable.document, notApplicable.output);
  assert.equal(result.valid, true, result.errors.join('; '));
});

test('fails byte drift even when the attacker rehashes the artifact manifest', (t) => {
  const { document, output } = generated(t);
  const setupPath = path.join(output, '.github', 'SETUP.md');
  fs.appendFileSync(setupPath, '\nUnreviewed drift.\n');
  const manifestPath = path.join(output, '.github', 'frootai-github-adapter.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  manifest.artifacts['.github/SETUP.md'] = sha256(fs.readFileSync(setupPath));
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  assert.match(errorsFor(document, output), /manifest drift detected|generated byte drift detected/);
});

test('rejects deprecated and unexpected generated formats', (t) => {
  const { document, output } = generated(t);
  const deprecatedPath = path.join(output, '.github', 'chatmodes', 'legacy.chatmode.md');
  fs.mkdirSync(path.dirname(deprecatedPath), { recursive: true });
  fs.writeFileSync(deprecatedPath, '# Legacy mode\n', 'utf8');
  const errors = errorsFor(document, output);
  assert.match(errors, /deprecated chat mode format/);
  assert.match(errors, /unexpected or stale generated artifact/);
});

test('rejects invalid skills, duplicate YAML keys, and malformed links', (t) => {
  const invalidName = generated(t);
  const skillPath = path.join(invalidName.output, '.github', 'skills', 'build-reference', 'SKILL.md');
  replace(skillPath, 'name: build-reference', 'name: wrong-skill');
  assert.match(errorsFor(invalidName.document, invalidName.output), /skill name must match its folder/);

  const duplicateKey = generated(t);
  const duplicatePath = path.join(duplicateKey.output, '.github', 'skills', 'build-reference', 'SKILL.md');
  replace(duplicatePath, 'description: ', 'description: "duplicate"\ndescription: ');
  assert.match(errorsFor(duplicateKey.document, duplicateKey.output), /invalid YAML.*Map keys must be unique/);

  const malformedLink = generated(t);
  const agentPath = path.join(malformedLink.output, '.github', 'agents', 'builder.agent.md');
  replace(agentPath, '../skills/build-reference/SKILL.md', '../skills/%ZZ/SKILL.md');
  assert.match(errorsFor(malformedLink.document, malformedLink.output), /malformed relative link/);
});

test('rejects unresolved handoffs, prompt agents, and relative resources', (t) => {
  const handoff = generated(t);
  replace(path.join(handoff.output, '.github', 'agents', 'builder.agent.md'), 'agent: "reviewer"', 'agent: "missing-reviewer"');
  assert.match(errorsFor(handoff.document, handoff.output), /unresolved or altered handoff/);

  const prompt = generated(t);
  replace(path.join(prompt.output, '.github', 'prompts', 'build-reference.prompt.md'), 'agent: "builder"', 'agent: "missing-builder"');
  assert.match(errorsFor(prompt.document, prompt.output), /unresolved or altered prompt agent/);

  const resource = generated(t);
  fs.rmSync(path.join(resource.output, '.github', 'skills', 'build-reference', 'SKILL.md'));
  const errors = errorsFor(resource.document, resource.output);
  assert.match(errors, /missing generated artifact/);
  assert.match(errors, /unresolved relative link/);
});

test('rejects widened, missing, deprecated, and globally applied tool policies', (t) => {
  const widened = generated(t);
  replace(path.join(widened.output, '.github', 'agents', 'builder.agent.md'), 'tools: ["edit","execute","read","search"]', 'tools: ["edit","execute","read","search","web"]');
  assert.match(errorsFor(widened.document, widened.output), /tools exceed or differ from the role policy/);

  const missing = generated(t);
  replace(path.join(missing.output, '.github', 'prompts', 'review-reference.prompt.md'), 'tools: ["execute","read","search"]\n', '');
  assert.match(errorsFor(missing.document, missing.output), /tools must be an explicit non-empty array/);

  const deprecated = generated(t);
  replace(path.join(deprecated.output, '.github', 'agents', 'reviewer.agent.md'), 'tools: ["execute","read","search"]', 'tools: ["codebase","read","search"]');
  assert.match(errorsFor(deprecated.document, deprecated.output), /deprecated tool alias: codebase/);

  const globalInstruction = generated(t);
  replace(path.join(globalInstruction.output, '.github', 'instructions', 'reference-implementation.instructions.md'), 'applyTo: ["reference/app/**","reference/tests/**"]', 'applyTo: ["**"]');
  assert.match(errorsFor(globalInstruction.document, globalInstruction.output), /global.*glob/);
});

test('rejects unbounded, unsupported, unresolved, and invalid hook programs', (t) => {
  const timeout = generated(t);
  const hookPath = path.join(timeout.output, '.github', 'hooks', 'frootai-hooks.json');
  const hooks = JSON.parse(fs.readFileSync(hookPath, 'utf8'));
  hooks.hooks.PreToolUse[0].timeout = 0;
  hooks.hooks.LegacyEvent = [{ type: 'command', command: 'node .github/hooks/missing.mjs', timeout: 30 }];
  fs.writeFileSync(hookPath, `${JSON.stringify(hooks, null, 2)}\n`, 'utf8');
  const errors = errorsFor(timeout.document, timeout.output);
  assert.match(errors, /timeout must be 1-15 seconds/);
  assert.match(errors, /unsupported hook event/);
  assert.match(errors, /unresolved hook script/);

  const syntax = generated(t);
  fs.appendFileSync(path.join(syntax.output, '.github', 'hooks', 'frootai-cloud-guard.mjs'), '\nif (\n');
  assert.match(errorsFor(syntax.document, syntax.output), /syntax check failed/);
});

test('rejects manifest traversal, stale files, and symbolic links', (t) => {
  const traversal = generated(t);
  const manifestPath = path.join(traversal.output, '.github', 'frootai-github-adapter.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  manifest.artifacts['../outside.json'] = '0'.repeat(64);
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
  assert.match(errorsFor(traversal.document, traversal.output), /artifact set mismatch|missing declared artifact/);

  const stale = generated(t);
  fs.writeFileSync(path.join(stale.output, '.github', 'stale.txt'), 'stale', 'utf8');
  assert.match(errorsFor(stale.document, stale.output), /unexpected or stale generated artifact/);

  const linked = generated(t);
  const outside = fs.mkdtempSync(path.join(os.tmpdir(), 'frootai-conformance-outside-'));
  t.after(() => fs.rmSync(outside, { recursive: true, force: true }));
  try {
    fs.symlinkSync(outside, path.join(linked.output, '.github', 'linked'), process.platform === 'win32' ? 'junction' : 'dir');
  } catch (error) {
    if (error.code === 'EPERM') return t.skip('symbolic link creation requires host privilege');
    throw error;
  }
  assert.match(errorsFor(linked.document, linked.output), /symbolic link is prohibited/);
});

test('CLI returns structured invalid evidence and a nonzero status', (t) => {
  const { output } = generated(t);
  fs.appendFileSync(path.join(output, '.github', 'SETUP.md'), '\ndrift\n');
  const result = spawnSync(process.execPath, [validatorPath, '--profile', path.join(fixtureRoot, 'applicable.json'), '--output', output], { cwd: root, encoding: 'utf8', shell: false });
  assert.equal(result.status, 1);
  const report = JSON.parse(result.stdout);
  assert.equal(report.status, 'invalid');
  assert.equal(report.errors.some((error) => /drift/.test(error)), true);
});